// Build the astrophysics rooms: node notes/astrophysics/build/build.mjs
// Writes game/content/astrophysics/<room>.json + index.json + codex.json, and a readable
// markdown study guide per room in notes/astrophysics/study/ (usable before the engine renders lessons).
import { writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import core from './rooms/core.mjs';

const ROOT = new URL('../../../', import.meta.url);
const OUT = new URL('game/content/astrophysics/', ROOT);
const STUDY = new URL('notes/astrophysics/study/', ROOT);
mkdirSync(OUT, { recursive: true }); mkdirSync(STUDY, { recursive: true });

// Room order = order of Choudhuri chapters (and very likely of the lecture).
const ORDER = ['photometry-radiation', 'radiative-transfer', 'stellar-forge', 'nuclear-furnace', 'degenerate-matter',
  'interstellar-medium', 'galactic-dynamics', 'active-galaxies', 'expanding-universe', 'early-universe', 'exam-hall'];
const SHORT = { 'photometry-radiation': 'light', 'radiative-transfer': 'rt', 'stellar-forge': 'forge', 'nuclear-furnace': 'nuc',
  'degenerate-matter': 'deg', 'interstellar-medium': 'ism', 'galactic-dynamics': 'dyn', 'active-galaxies': 'agn',
  'expanding-universe': 'cosmo', 'early-universe': 'early', 'exam-hall': 'exam' };

const rooms = structuredClone(core);
let codex = [];
const files = readdirSync(new URL('rooms/', import.meta.url)).filter((f) => f.endsWith('.mjs') && f !== 'core.mjs').sort();
for (const f of files) {
  const mod = await import(`./rooms/${f}`);
  for (const [key, room] of Object.entries(mod.rooms || {})) {
    if (rooms[key]) throw new Error(`${f}: room ${key} already exists`);
    rooms[key] = room;
  }
  for (const [key, encs] of Object.entries(mod.extend || {})) {
    if (!rooms[key]) throw new Error(`${f}: cannot extend missing room ${key}`);
    rooms[key].encounters.push(...encs);
  }
  for (const [key, srcs] of Object.entries(mod.sources || {})) rooms[key].sources.push(...srcs);
  codex = codex.concat(mod.codex || []);
}

const RANK = { lesson: 0, quiz: 1, 'predict-observe': 2, derive: 3, calc: 4, boss: 5 };
const fixPow = (e) => e.replace(/\^/g, '**'); // JS ^ is XOR
const ids = ORDER.filter((k) => rooms[k]);
for (const k of Object.keys(rooms)) if (!ORDER.includes(k)) throw new Error(`room ${k} missing from ORDER`);

for (const key of ids) {
  const room = rooms[key], pre = `astro-${SHORT[key]}-`;
  // stable sort: lessons first (theory before the fight), bosses last
  room.encounters = room.encounters.map((e, i) => [e, i]).sort((a, b) => (RANK[a[0].type] - RANK[b[0].type]) || (a[1] - b[1])).map((x) => x[0]);
  const seen = new Set();
  for (const e of room.encounters) {
    if (seen.has(e.id)) throw new Error(`${key}: duplicate id ${e.id}`);
    seen.add(e.id);
    e.id = pre + e.id;
    if (e.requires) e.requires = pre + e.requires;
    if (e.type === 'calc') for (const s of e.steps) s.answer = fixPow(s.answer);
    for (const a of e.finalAnswers || []) a.answer = fixPow(a.answer);
  }
  writeFileSync(new URL(key + '.json', OUT), JSON.stringify(room, null, 2) + '\n');
  writeFileSync(new URL(key + '.md', STUDY), toMarkdown(room));
}
writeFileSync(new URL('index.json', OUT), JSON.stringify({ region: 'Astro Observatory Ship', rooms: ids, codex: 'codex.json' }, null, 2) + '\n');
writeFileSync(new URL('codex.json', OUT), JSON.stringify({ course: 'astrophysics', entries: codex }, null, 2) + '\n');
writeFileSync(new URL('00-formula-codex.md', STUDY), codexMarkdown(codex));
writeFileSync(new URL('README.md', STUDY), `# Astrophysics study guides (generated)\n\nGenerated by \`node notes/astrophysics/build/build.mjs\` from the same data as the game rooms. Do not edit by hand.\nRead in this order (Choudhuri chapter order):\n\n0. [Formula codex](00-formula-codex.md): every formula with its meaning, for the 4-page exam sheet\n${ids.map((k, i) => `${i + 1}. [${rooms[k].title}](${k}.md): ${rooms[k].topics.join(', ')}`).join('\n')}\n`);
console.log('rooms:', ids.map((k) => `${k} (${rooms[k].encounters.length})`).join(', '), '| codex entries:', codex.length);

// ---------- markdown export ----------
function mcMd(m, n) {
  const L = 'ABCD';
  return `${n ? `**${n}.** ` : ''}${m.q}\n\n${m.options.map((o, i) => `- ${L[i]}) ${o}`).join('\n')}\n\n<details><summary>Answer</summary>\n\n**${L[m.correct]}**. ${m.explain}${m.source ? ` *(${m.source.where})*` : ''}\n\n</details>\n`;
}
function toMarkdown(room) {
  const out = [`# ${room.title}`, '', `*${room.region}. Topics: ${room.topics.join(', ')}.*`, '', room.intro, '',
    '**Sources:** ' + room.sources.map((s) => `${s.file.split('/').pop()} (${s.where})`).join('; '), ''];
  const BL = { intuition: '💡 **Intuition.** ', pitfall: '⚠️ **Pitfall.** ', figure: '🖼️ **Picture it.** ', exam: '📝 **How the exam asks it.** ' };
  for (const e of room.encounters) {
    if (e.type === 'lesson') {
      out.push(`## 📖 ${e.title}${e.tier === 'intuition' ? ' (intuition)' : ''}`, '');
      for (const b of e.blocks) out.push(b.kind === 'eq' ? `$$${b.tex}$$${b.label ? `  \n*${b.label}*` : ''}` : (BL[b.kind] || '') + b.html, '');
      if (e.check?.length) { out.push('### Check yourself', ''); e.check.forEach((m, i) => out.push(mcMd(m, i + 1))); }
    } else if (e.type === 'quiz') {
      out.push(`## ❓ Quiz: ${e.title}`, '', '*Exam-style multiple choice (3 pt each in the real exam).*', '');
      e.questions.forEach((m, i) => out.push(mcMd(m, i + 1)));
    } else if (e.type === 'derive') {
      out.push(`## ✍️ Derivation: ${e.title}`, '', `*${e.source.where}*`, '', `**Goal:** ${e.goal}`, '');
      if (e.given?.length) out.push('**Given:** ' + e.given.join('; '), '');
      e.steps.forEach((s, i) => out.push(`${i + 1}. ${s.prompt}`, '', `   <details><summary>Reveal</summary>\n\n   ${s.reveal}\n\n   </details>`, ''));
      if (e.keyPoints?.length) out.push('**Full marks needs:** ' + e.keyPoints.join(' · '), '');
    } else if (e.type === 'calc') {
      out.push(`## 🔢 ${e.fight === 'fermi' ? 'Quick fight' : 'Calculation'}: ${e.title}`, '', e.problem, '');
      e.steps.forEach((s, i) => out.push(`${i + 1}. ${s.prompt} *[${s.unit}]*`, '', `   <details><summary>Hint</summary>\n\n   ${s.hint}\n\n   </details>`, ''));
    } else if (e.type === 'boss') {
      out.push(`## 👹 ${e.title}`, '', `*${e.source.where}, ${e.minutes} min.*`, '', ...e.statement.flatMap((x) => [x, '']));
      out.push('<details><summary>Key points of a full-marks solution</summary>', '', ...e.keyPoints.map((k) => `- ${k}`), '', '</details>', '');
    }
  }
  return out.join('\n');
}
function codexMarkdown(entries) {
  const groups = {};
  for (const e of entries) (groups[e.group] ||= []).push(e);
  const out = ['# Formula codex (astrophysics)', '', 'Every formula used in the rooms, with what it means and when to use it. This is a draft for your 4-page exam sheet.', ''];
  for (const [g, es] of Object.entries(groups)) {
    out.push(`## ${g}`, '');
    for (const e of es) out.push(`**${e.title}**  \n$$${e.tex}$$`, `${e.meaning}${e.when ? ` *Use when:* ${e.when}` : ''}${e.source ? ` *(${e.source})*` : ''}`, '');
  }
  return out.join('\n');
}
