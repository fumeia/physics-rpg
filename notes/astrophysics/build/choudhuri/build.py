"""Build game/content/astrophysics/choudhuri-exercises.json: every end-of-chapter exercise of Choudhuri,
"Astrophysics for Physicists", as a book exercise (derivation-type encounter with its own console) in the matching room.
Numbers in the solutions come from calc.py (placeholders <<exercise.key>> in part*.py).
Run: python3 build.py   (needs scipy)"""
import json, re, os
from math import log10, floor
from calc import N
import part1, part2, part3

PAGES = {1: '22', 2: '57-59', 3: '89-90', 4: '124-125', 5: '149-151', 6: '194-196', 7: '217-218', 8: '257-259',
         9: '296', 10: '324', 11: '353-355', 12: '384-385', 13: '416-417', 14: '440-441'}
SRC = 'materials/astrophysics/scripts/Choudhuri_Textbook.pdf'

def num(v):
    v = float(v); a = abs(v)
    if a == 0: return '0'
    if 0.01 <= a < 1e4:
        s = f'{v:.3g}'
        return s
    ex = floor(log10(a)); m = v / 10 ** ex
    if round(m, 1) >= 10: m /= 10; ex += 1
    return f'{m:.2g}\\times10^{{{ex}}}' if f'{m:.2g}' != '1' else f'10^{{{ex}}}'

def table(rows, xfmt=lambda x: num(x)):
    return '; '.join(f'$T={int(T)}$ K: $x={xfmt(x)}$' for T, x in rows)

def fill(s):
    def rep(m):
        key = m.group(1); ex, field = key.rsplit('.', 1)
        v = N[ex][field]
        if isinstance(v, list): return table(v)
        return num(v)
    # a number written outside $...$ that needs LaTeX (\times10^) gets its own $...$
    s = re.sub(r'<<([0-9]+\.[0-9]+\.[A-Za-z0-9_]+)>>', lambda m: (lambda t: t if s[:m.start()].count('$') % 2 or '\\' not in t or isinstance(N[m.group(1).rsplit('.', 1)[0]][m.group(1).rsplit('.', 1)[1]], list) else f'${t}$')(rep(m)), s)
    assert '<<' not in s, s
    # \' in the sources: a prime inside $...$, an apostrophe in text
    parts = s.split('$')
    return '$'.join(p.replace("\\'", "'" if i % 2 else '\u2019') for i, p in enumerate(parts))

items = []
for part in (part1, part2, part3):
    for e in part.EX:
        ch = int(e['num'].split('.')[0])
        given = [fill(g) for g in e['given']]
        if e.get('note'): given.append('<i>Note: ' + fill(e['note']) + '</i>')
        enc = {'type': 'derive', 'book': True, 'id': 'astro-book-' + e['num'].replace('.', '-'),
               'title': f"Choudhuri {e['num']}: " + fill(e['title']), 'xp': e['xp'],
               'source': {'file': SRC, 'where': f"Choudhuri, Exercise {e['num']} (end of Ch. {ch}, p. {PAGES[ch]})"},
               'goal': fill(e['goal']), 'given': given,
               'steps': [{'prompt': fill(p), 'reveal': fill(r)} for p, r in e['steps']],
               'keyPoints': [fill(k) for k in e['keys']]}
        items.append({'room': e['room'], 'enc': enc})

nums = [i['enc']['id'] for i in items]
assert len(nums) == len(set(nums)), 'duplicate exercise'
out = {'about': 'Every end-of-chapter exercise of Choudhuri, Astrophysics for Physicists (Cambridge 2010), with a worked solution. '
                'Generated by notes/astrophysics/build/choudhuri/build.py; numbers from calc.py (book constants, Appendix A).',
       'items': items}
dst = os.path.join(os.path.dirname(__file__), '../../../../game/content/astrophysics/choudhuri-exercises.json')
with open(dst, 'w') as fh: json.dump(out, fh, ensure_ascii=False, indent=1)
print(len(items), 'exercises ->', os.path.normpath(dst))
